import assert from 'node:assert/strict';
import {observePurchases, summarizePurchases} from './purchase-observer.mjs';
const game = {cookies: 100, buyBulk: 100, buyMode: 1, Upgrades: {}};
const item = {id: 2, amount: 0, getPrice: () => 20, buy() {
  assert.equal(this, item); game.cookies -= 20; this.amount++; return 42;
}};
game.ObjectsById = [item];
const original = item.buy, observer = observePurchases(game, {getBankCookies: () => 10}, 1);
assert.equal(item.buy(), 42);
assert.equal(observer.rows[0].units, 1); assert.equal(observer.rows[0].spent, 20);
assert.equal(observer.rows[0].before.bank, 10);
assert.equal(observer.rows[0].bulkViolation.expectedUnits, 100);
assert.equal(observer.rows[0].bulkViolation.requestedUnits, null);
assert.match(observer.rows[0].bulkViolation.stack, /Building purchase ended off selected multiple/);
item.buy(); assert.equal(observer.truncated, true); observer.restore();
assert.equal(item.buy, original);
const failing = () => {throw Error('buy failed');}; item.buy = failing;
const second = observePurchases(game, {getBankCookies: () => 10});
assert.throws(() => item.buy(), /buy failed/); assert.equal(second.rows.length, 1);
const replacement = () => {}; item.buy = replacement; second.restore(); assert.equal(item.buy, replacement);
assert.throws(() => observePurchases(game, {}, 0), /Invalid/);
item.amount = 199; game.cookies = 100; item.buy = original;
const complement = observePurchases(game, {getBankCookies: () => 10});
item.buy(1);
assert.equal(complement.rows[0].after.owned, 200);
assert.equal(complement.rows[0].bulkViolation, undefined);
complement.restore();
item.amount = 123;
const partial = observePurchases(game, {getBankCookies: () => 10});
item.buy(7);
assert.equal(partial.rows[0].bulkViolation.requestedUnits, 7);
assert.equal(partial.rows[0].bulkViolation.expectedUnits, 77);
partial.restore();
const good = {units: 1, spent: 20, before: {cookies: 100, bank: 60}, after: {cookies: 80, bank: 60}};
assert.equal(summarizePurchases({rows: [good], truncated: false}).observedReservePass, true);
assert.equal(summarizePurchases({rows: [good], truncated: true}).observedReservePass, false);
assert.equal(summarizePurchases({rows: [], truncated: false}).observedReservePass, false);
assert.equal(summarizePurchases({rows: [{...good, after: {cookies: 50, bank: 60}}], truncated: false}).violations, 1);
assert.equal(summarizePurchases({rows: [{...good, spent: null}], truncated: false}).paymentAnomalies, 1);
assert.equal(summarizePurchases({rows: [{...good, after: {cookies: null, bank: 60}}], truncated: false}).observedReservePass, false);
console.log('purchase observer: native result, payment, limit, failure and restoration pass');
